// Migration check: builds supabase/checks/migration-check.sql, a read-only query that lists every
// migration that hasn't fully run on a database (missing functions or columns, or an older
// version of a function). It runs all migrations on a throwaway in-memory Postgres, records
// what each one leaves behind, and writes that list into the query. See "Migration check" in
// the README. Run it again after adding a migration:
//
//   npm i --no-save @electric-sql/pglite      (once)
//   node scripts/migration-check/make.mjs

let PGlite, citext, pg_trgm;
try {
  ({ PGlite } = await import("@electric-sql/pglite"));
  ({ citext } = await import("@electric-sql/pglite/contrib/citext"));
  ({ pg_trgm } = await import("@electric-sql/pglite/contrib/pg_trgm"));
} catch {
  console.error("Needs PGlite: npm i --no-save @electric-sql/pglite");
  process.exit(2);
}
import fs from "node:fs";

const root = new URL("../../", import.meta.url).pathname;
const dir = `${root}supabase/migrations`;
const db = new PGlite({ extensions: { citext, pg_trgm } });
// Just enough of Supabase's auth and storage schemas for the migrations to run.
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema auth; grant usage on schema auth to anon, authenticated;
create table auth.users (id uuid primary key, email text, raw_user_meta_data jsonb default '{}', is_anonymous boolean default false);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.uid', true), '')::uuid $$;
create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt', true), ''), '{}')::jsonb $$;
grant execute on function auth.uid(), auth.jwt() to anon, authenticated;
grant usage on schema public to anon, authenticated;
-- Supabase's defaults for the public schema:
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on functions to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
create schema storage; grant usage on schema storage to anon, authenticated;
create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text, owner uuid);
create function storage.foldername(name text) returns text[] language sql as $$ select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'),1)-1] $$;
grant execute on function storage.foldername(text) to anon, authenticated;`);
const q = async (s) => (await db.query(s)).rows;

const fns = async () =>
  new Map(
    (await q(`select p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' n, md5(p.prosrc) h
              from pg_proc p join pg_namespace s on s.oid = p.pronamespace where s.nspname = 'public' and p.prokind = 'f'`)).map((r) => [r.n, r.h]),
  );
const cols = async () =>
  new Set((await q(`select table_name || '.' || column_name n from information_schema.columns where table_schema = 'public'`)).map((r) => r.n));

let prevF = await fns();
let prevC = await cols();
const baseF = new Set(prevF.keys());
const baseC = new Set(prevC);
const lastF = new Map(); // function → the last migration that changed it
const firstC = new Map(); // column → the migration that added it
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(fs.readFileSync(`${dir}/${f}`, "utf8"));
  const nf = await fns();
  const nc = await cols();
  for (const [k, h] of nf) if (prevF.get(k) !== h) lastF.set(k, f);
  for (const c of nc) if (!prevC.has(c) && !firstC.has(c)) firstC.set(c, f);
  prevF = nf;
  prevC = nc;
}

const esc = (s) => s.replace(/'/g, "''");
const fRows = [...prevF].filter(([k]) => !baseF.has(k)).sort().map(([k, h]) => `  ('${esc(k)}', '${h}', '${lastF.get(k)}')`);
const cRows = [...prevC].filter((c) => !baseC.has(c)).sort().map((c) => `  ('${esc(c)}', '${firstC.get(c)}')`);
const sql = `-- Did every migration run? Paste into the Supabase SQL editor and run. Read-only.
-- No rows = everything is in place. Otherwise each row names a migration that hasn't (fully) run
-- and what's missing. Generated by scripts/migration-check/make.mjs; don't edit by hand.
with want_fn(fn, hash, migration) as (values
${fRows.join(",\n")}
), want_col(col, migration) as (values
${cRows.join(",\n")}
), have_fn as (
  select p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' fn, md5(p.prosrc) hash
  from pg_proc p join pg_namespace s on s.oid = p.pronamespace where s.nspname = 'public' and p.prokind = 'f'
), have_col as (
  select table_name || '.' || column_name col from information_schema.columns where table_schema = 'public'
), problems as (
  select w.migration, w.fn as what, case when h.fn is null then 'missing' else 'older version' end as state
  from want_fn w left join have_fn h on h.fn = w.fn
  where h.fn is null or h.hash <> w.hash
  union all
  select w.migration, w.col, 'missing column'
  from want_col w left join have_col h on h.col = w.col
  where h.col is null
)
select migration, count(*) as problems, string_agg(what || ' (' || state || ')', ', ' order by what) as details
from problems group by migration order by migration;
`;
fs.mkdirSync(`${root}supabase/checks`, { recursive: true });
fs.writeFileSync(`${root}supabase/checks/migration-check.sql`, sql);
console.log(`supabase/checks/migration-check.sql: ${fRows.length} functions, ${cRows.length} columns`);
